<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\AiGeneration;
use App\Models\Project;
use App\Models\ScriptDraft;
use App\Models\ScriptVersion;
use App\Services\AI\Exceptions\ProviderConfigurationException;
use App\Services\AI\Exceptions\ProviderException;
use App\Services\AI\ScriptGenerator;
use App\Services\AI\ScriptResult;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

class ScriptGenerationController extends Controller
{
    public function __construct(private readonly ScriptGenerator $generator) {}

    public function store(Request $request, string $project): JsonResponse
    {
        $validated = $request->validate([
            'max_scenes' => ['sometimes', 'integer', 'min:1', 'max:10'],
            'include_closing' => ['sometimes', 'boolean'],
        ]);

        $projectModel = $request->user()
            ->projects()
            ->with('contentBrief')
            ->findOrFail($project);

        if (! $projectModel->contentBrief) {
            return response()->json([
                'message' => 'Content brief not found for this project.',
            ], 422);
        }

        $generation = AiGeneration::create([
            'project_id' => $projectModel->id,
            'task_type' => 'script_generation',
            'provider' => (string) config('services.ai.provider', 'mock'),
            'model' => null,
            'status' => 'pending',
            'input_summary' => [
                'project' => [
                    'platform' => $projectModel->platform,
                    'aspect_ratio' => $projectModel->aspect_ratio,
                    'target_duration_seconds' => $projectModel->target_duration_seconds,
                ],
                'brief' => [
                    'topic' => $projectModel->contentBrief->topic,
                    'category' => $projectModel->contentBrief->category,
                    'target_audience' => $projectModel->contentBrief->target_audience,
                    'content_goal' => $projectModel->contentBrief->content_goal,
                    'tone' => $projectModel->contentBrief->tone,
                    'additional_instructions' => $projectModel->contentBrief->additional_instructions,
                ],
                'options' => $validated,
            ],
            'started_at' => now(),
        ]);

        try {
            $provider = $this->generator->provider();
            $generation->update(['model' => $provider->model()]);

            $result = $this->generator->generate($projectModel, $projectModel->contentBrief, $validated);

            $content = $this->formatScriptContent($result);

            DB::transaction(function () use ($projectModel, $result, $content, $generation) {
                // Serialize version allocation per project to avoid duplicate
                // version_number values under concurrent requests.
                Project::whereKey($projectModel->id)->lockForUpdate()->first();

                $nextVersion = (int) ScriptVersion::where('project_id', $projectModel->id)
                    ->max('version_number') + 1;

                ScriptVersion::create([
                    'project_id' => $projectModel->id,
                    'version_number' => $nextVersion,
                    'title' => $result->title,
                    'content' => $content,
                    'change_summary' => 'Generated by '.$generation->provider,
                    'created_by' => $projectModel->user_id,
                ]);

                ScriptDraft::updateOrCreate(
                    ['project_id' => $projectModel->id],
                    [
                        'title' => $result->title,
                        'content' => $content,
                        'updated_by' => $projectModel->user_id,
                    ],
                );

                $generation->update([
                    'status' => 'completed',
                    'result_summary' => [
                        'title' => $result->title,
                        'scene_count' => $result->sceneCount(),
                        'hook' => $result->hook,
                        'closing_cta' => $result->closingCta,
                    ],
                    'finished_at' => now(),
                ]);
            });

            return response()->json([
                'message' => 'Script generated successfully.',
                'data' => [
                    'generation_id' => $generation->id,
                    'provider' => $generation->provider,
                    'title' => $result->title,
                    'hook' => $result->hook,
                    'closing_cta' => $result->closingCta,
                    'scenes' => $result->toArray()['scenes'],
                    'content' => $content,
                ],
            ], 201);
        } catch (ProviderConfigurationException $e) {
            $generation->update([
                'status' => 'failed',
                'error_code' => 'provider_configuration_error',
                'finished_at' => now(),
            ]);

            return response()->json([
                'message' => 'Script generation is not configured correctly.',
                'error' => 'Script generation is unavailable at this time.',
            ], 500);
        } catch (ProviderException $e) {
            $generation->update([
                'status' => 'failed',
                'error_code' => 'provider_error',
                'finished_at' => now(),
            ]);

            return response()->json([
                'message' => 'Script generation failed.',
                'error' => 'Unable to generate script at this time.',
            ], 502);
        } catch (\Throwable $e) {
            $generation->update([
                'status' => 'failed',
                'error_code' => 'internal_error',
                'finished_at' => now(),
            ]);

            return response()->json([
                'message' => 'Script generation failed.',
                'error' => 'Unable to generate script at this time.',
            ], 500);
        }
    }

    private function formatScriptContent(ScriptResult $result): string
    {
        $lines = [];
        $lines[] = "Title: {$result->title}";

        if ($result->hook) {
            $lines[] = "Hook: {$result->hook}";
        }

        $lines[] = '';

        foreach ($result->scenes as $scene) {
            $lines[] = "Scene {$scene->sceneNumber}";

            if ($scene->visualDirection) {
                $lines[] = "Visual: {$scene->visualDirection}";
            }

            if ($scene->estimatedDurationSeconds) {
                $lines[] = "Duration: {$scene->estimatedDurationSeconds}s";
            }

            $lines[] = "Narration: {$scene->narration}";
            $lines[] = '';
        }

        if ($result->closingCta) {
            $lines[] = "Closing CTA: {$result->closingCta}";
        }

        return trim(implode("\n", $lines));
    }
}
